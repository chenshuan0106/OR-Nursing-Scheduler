"""
Compare generated BOR schedule output against a reference workbook.

This is a small local regression helper for debugging the scheduling rules.
It compares the visible cell values in the formal schedule sheets, while
ignoring the optional "排班前核對" sheet generated by this project.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path
from typing import Iterable

from openpyxl import load_workbook


def _normalize(value):
    if value is None:
        return ''
    return str(value).replace('\r\n', '\n').strip()


def _canonical(value: str) -> str:
    return (
        value
        .replace('白斑', '白班')
        .replace('\n(原', '\n原')
        .replace(')', '')
        .replace('#', '')
        .strip()
    )


def _extract_shift_entries(value: str) -> list[str]:
    value = _normalize(value)
    if not value:
        return []
    entries = []
    for match in re.finditer(r'(?:補)?\d{1,2}/\d{1,2}\s*(?:白班|白斑|小夜|大夜)', value):
        entries.append(_canonical(match.group(0)).replace(' ', ''))
    for match in re.finditer(r'\d+月(?:大P1|小P1|大P2|小P2|換心|補)', value):
        entries.append(match.group(0))
    for match in re.finditer(r'\d+月待補班(?:\n一次假日值班)?', value):
        entries.append(match.group(0).replace('\n一次假日值班', ''))
    return entries


def _sheet_pairs(actual_sheets: list[str], expected_sheets: list[str]) -> list[tuple[str, str]]:
    actual_formal = [name for name in actual_sheets if name != '排班前核對']
    if len(actual_formal) != len(expected_sheets):
        return list(zip(actual_formal, expected_sheets))

    pairs = []
    for expected_name in expected_sheets:
        matched = None
        for actual_name in actual_formal:
            if actual_name == expected_name or expected_name in actual_name:
                matched = actual_name
                break
        pairs.append((matched or actual_formal[len(pairs)], expected_name))
    return pairs


def compare_workbooks(
    actual_path: Path,
    expected_path: Path,
    columns: Iterable[int] | None = None,
    classify_format: bool = False,
) -> int:
    actual_wb = load_workbook(actual_path, data_only=False)
    expected_wb = load_workbook(expected_path, data_only=False)

    try:
        pairs = _sheet_pairs(actual_wb.sheetnames, expected_wb.sheetnames)
        total_diffs = 0

        print(f'actual:   {actual_path.name} sheets={actual_wb.sheetnames}')
        print(f'expected: {expected_path.name} sheets={expected_wb.sheetnames}')

        for actual_sheet, expected_sheet in pairs:
            actual_ws = actual_wb[actual_sheet]
            expected_ws = expected_wb[expected_sheet]

            cols = list(columns) if columns else list(range(1, max(actual_ws.max_column, expected_ws.max_column) + 1))
            sheet_diffs = []
            format_only_diffs = 0

            max_row = max(actual_ws.max_row, expected_ws.max_row)
            for row in range(1, max_row + 1):
                actual_name = _normalize(actual_ws.cell(row=row, column=1).value)
                expected_name = _normalize(expected_ws.cell(row=row, column=1).value)

                for col in cols:
                    actual_value = _normalize(actual_ws.cell(row=row, column=col).value)
                    expected_value = _normalize(expected_ws.cell(row=row, column=col).value)
                    if actual_value != expected_value:
                        is_format_only = _canonical(actual_value) == _canonical(expected_value)
                        if is_format_only:
                            format_only_diffs += 1
                        sheet_diffs.append((row, col, actual_name, expected_name, actual_value, expected_value, is_format_only))

            total_diffs += len(sheet_diffs)
            material_diffs = len(sheet_diffs) - format_only_diffs
            detail = f', format_only={format_only_diffs}, material={material_diffs}' if classify_format else ''
            print(f'\n[{actual_sheet} vs {expected_sheet}] diffs={len(sheet_diffs)}{detail}')
            for row, col, actual_name, expected_name, actual_value, expected_value, is_format_only in sheet_diffs[:120]:
                name_text = actual_name or expected_name or f'row {row}'
                tag = ' [format]' if classify_format and is_format_only else ''
                print(f'  R{row}C{col} {name_text}: actual={actual_value!r} expected={expected_value!r}{tag}')
            if len(sheet_diffs) > 120:
                print(f'  ... {len(sheet_diffs) - 120} more')

        print(f'\nTOTAL_DIFFS={total_diffs}')
        return total_diffs
    finally:
        actual_wb.close()
        expected_wb.close()


def _entry_sort_key(item: str) -> tuple[int, int, str]:
    return (
        int(item.split('/')[0]) if '/' in item else 98,
        int(re.search(r'/(\d+)', item).group(1)) if '/' in item else 0,
        item,
    )


def _collect_holiday_entries(ws, columns: Iterable[int]) -> dict[str, list[str]]:
    entries: dict[str, list[str]] = {}
    for row in range(1, ws.max_row + 1):
        name = _normalize(ws.cell(row=row, column=1).value).lstrip('*')
        if not name:
            continue
        for col in columns:
            for entry in _extract_shift_entries(_normalize(ws.cell(row=row, column=col).value)):
                entries.setdefault(entry, []).append(name)
    return entries


def summarize_holiday_diffs(actual_path: Path, expected_path: Path, source_path: Path | None = None) -> int:
    actual_wb = load_workbook(actual_path, data_only=False)
    expected_wb = load_workbook(expected_path, data_only=False)
    source_wb = load_workbook(source_path, data_only=True) if source_path else None

    try:
        pairs = _sheet_pairs(actual_wb.sheetnames, expected_wb.sheetnames)
        total = 0
        for actual_sheet, expected_sheet in pairs:
            actual_ws = actual_wb[actual_sheet]
            expected_ws = expected_wb[expected_sheet]

            actual_entries = _collect_holiday_entries(actual_ws, range(6, 10))
            expected_entries = _collect_holiday_entries(expected_ws, range(6, 10))
            source_entries = {}
            if source_wb:
                source_sheet = next((name for name in source_wb.sheetnames if expected_sheet in name or name in actual_sheet), None)
                if source_sheet:
                    source_entries = _collect_holiday_entries(source_wb[source_sheet], range(5, 9))

            keys = sorted(set(actual_entries) | set(expected_entries), key=_entry_sort_key)

            diffs = []
            for key in keys:
                actual_names = actual_entries.get(key, [])
                expected_names = expected_entries.get(key, [])
                if actual_names != expected_names:
                    diffs.append((key, actual_names, expected_names))

            total += len(diffs)
            print(f'\n[{actual_sheet} vs {expected_sheet}] holiday entry mismatches={len(diffs)}')
            for key, actual_names, expected_names in diffs:
                source_note = f' source={source_entries.get(key, [])}' if source_entries else ''
                print(f'  {key}: actual={actual_names or []} expected={expected_names or []}{source_note}')

        print(f'\nTOTAL_ENTRY_MISMATCHES={total}')
        return total
    finally:
        actual_wb.close()
        expected_wb.close()
        if source_wb:
            source_wb.close()


def print_holiday_rounds(actual_path: Path, expected_path: Path) -> int:
    actual_wb = load_workbook(actual_path, data_only=False)
    expected_wb = load_workbook(expected_path, data_only=False)

    try:
        pairs = _sheet_pairs(actual_wb.sheetnames, expected_wb.sheetnames)
        total = 0
        for actual_sheet, expected_sheet in pairs:
            actual_ws = actual_wb[actual_sheet]
            expected_ws = expected_wb[expected_sheet]
            print(f'\n[{actual_sheet} vs {expected_sheet}]')
            for round_num, col in enumerate(range(6, 10), 1):
                print(f'  ROUND {round_num}')
                rows = []
                max_row = max(actual_ws.max_row, expected_ws.max_row)
                for row in range(1, max_row + 1):
                    name = _normalize(actual_ws.cell(row=row, column=1).value) or _normalize(expected_ws.cell(row=row, column=1).value)
                    if not name:
                        continue
                    actual_value = _normalize(actual_ws.cell(row=row, column=col).value)
                    expected_value = _normalize(expected_ws.cell(row=row, column=col).value)
                    if actual_value or expected_value:
                        rows.append((name, actual_value, expected_value))
                        if actual_value != expected_value:
                            total += 1
                for name, actual_value, expected_value in rows:
                    marker = '' if actual_value == expected_value else ' *'
                    print(f'    {name}: actual={actual_value!r} expected={expected_value!r}{marker}')

        print(f'\nTOTAL_ROUND_DIFFS={total}')
        return total
    finally:
        actual_wb.close()
        expected_wb.close()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('actual', type=Path)
    parser.add_argument('expected', type=Path)
    parser.add_argument(
        '--holiday-only',
        action='store_true',
        help='Compare only the four holiday columns F:I.',
    )
    parser.add_argument(
        '--classify-format',
        action='store_true',
        help='Mark likely formatting-only differences, such as 白班/白斑 or optional 原班 parentheses.',
    )
    parser.add_argument(
        '--summary',
        action='store_true',
        help='Summarize holiday differences by date/shift entry instead of raw cell coordinates.',
    )
    parser.add_argument(
        '--source',
        type=Path,
        help='Optional input workbook to show where holiday entries came from in the previous sheet.',
    )
    parser.add_argument(
        '--rounds',
        action='store_true',
        help='Print holiday columns as rounds, showing actual vs expected values row by row.',
    )
    args = parser.parse_args()

    if args.rounds:
        diff_count = print_holiday_rounds(args.actual, args.expected)
        return 1 if diff_count else 0

    if args.summary:
        diff_count = summarize_holiday_diffs(args.actual, args.expected, args.source)
        return 1 if diff_count else 0

    columns = range(6, 10) if args.holiday_only else None
    diff_count = compare_workbooks(args.actual, args.expected, columns, args.classify_format)
    return 1 if diff_count else 0


if __name__ == '__main__':
    raise SystemExit(main())
